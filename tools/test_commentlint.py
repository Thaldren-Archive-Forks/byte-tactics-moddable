"""Tests for commentlint.py, on temporary git repositories.

    uv run tools/test_commentlint.py
"""

import contextlib
import io
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

import commentlint

GIT = ["git", "-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false"]


class Repo:
    def __init__(self, tmp):
        self.root = Path(tmp)
        self.run("init", "-q")
        self.write("README", "base\n")
        self.commit("base")

    def run(self, *args):
        subprocess.run([*GIT, *args], cwd=self.root, check=True, capture_output=True)

    def write(self, path, text):
        p = self.root / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)

    def commit(self, message):
        self.run("add", "-A")
        self.run("commit", "-q", "-m", message)

    def lint(self, fetch=None):
        return commentlint.lint(str(self.root), "HEAD~1...HEAD", fetch=fetch)[0]


class CommentLintTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = Repo(self.tmp.name)

    def check(self, path, text, expect_lines=()):
        self.repo.write(path, text)
        self.repo.commit("change")
        found = self.repo.lint()
        self.assertEqual([line for _, line, _ in found], list(expect_lines), found)

    def test_allowed_c_forms(self):
        self.check("src/a.cpp", "// FUNCTION: 0x4b6c30\nint f() { return 0; }\n"
                                "/* FUNCTION: 0x4b6c30 */\n// GLOBAL: 0x4fcca8\nint g;\n"
                                "// ENTRY: 0x4cbcd5 _Blit\n// FLAGS: /Gi\n"
                                "// TODO(#12): finish\nint h; // TODO(#12): finish\n")

    def test_allowed_python_forms(self):
        self.check("tools/a.py", '#!/usr/bin/env python3\n"""Doc."""\n# TODO(#12): finish\n'
                                 'def f():\n    """Docstring."""\n    return 1  # TODO(#12): finish\n')

    def test_stray_slash_comment(self):
        self.check("src/a.cpp", "int a;\n// explain why\nint b;\n", [2])

    def test_stray_trailing_comment(self):
        self.check("src/a.cpp", "int a; // why\n", [1])

    def test_stray_block_comment(self):
        self.check("src/a.cpp", "int a;\n/* explain */\n", [2])

    def test_added_block_reported_once(self):
        self.check("src/a.cpp", "int a;\n/*\n * one\n * two\n */\nint b;\n", [2])

    def test_block_started_on_added_line(self):
        self.repo.write("src/a.cpp", "int a;\n")
        self.repo.commit("old")
        self.repo.write("src/a.cpp", "int a; /* start\nmore */\n")
        self.repo.commit("change")
        self.assertEqual([line for _, line, _ in self.repo.lint()], [1])

    def test_old_comment_not_reported(self):
        self.repo.write("src/a.cpp", "// old note\nint a;\n")
        self.repo.commit("old")
        self.repo.write("src/a.cpp", "// old note\nint a;\nint b;\n")
        self.repo.commit("change")
        self.assertEqual(self.repo.lint(), [])

    def test_slashes_in_c_strings(self):
        self.check("src/a.cpp", 'const char *u = "http://x"; char c = \'"\';\n'
                                'const char *v = "a /* b */ c";\nint n = 1\'000;\n')

    def test_r_quote_after_identifier_is_not_raw(self):
        self.check("src/a.cpp", '#define STR(x) x\nconst char* s = STR"x"; // stray\n', [2])
        self.check("src/b.cpp", 'const char* s = FOOR"x"; // stray\n', [1])

    def test_raw_string_with_slashes(self):
        self.check("src/a.cpp", 'const char* s = R"x(a // b /* c )" )x"; const char* t = u8R"(//)";\n')

    def test_stray_python_comment(self):
        self.check("tools/a.py", "x = 1\n# note\n", [2])

    def test_hash_in_python_string(self):
        self.check("tools/a.py", 'x = "# not a comment"\ny = """\n# nor this\n"""\n')

    def test_python_docstring_exempt(self):
        self.check("tools/a.py", '"""# Module doc.\n\nSeveral lines.\n"""\n')

    def test_shebang_exempt_only_on_line_one(self):
        self.check("tools/a.py", "#!/usr/bin/env python3\nx = 1\n#!not a shebang\n", [3])

    def test_generated_file_exempt(self):
        self.check("src/harness/trace_schema.h", "// stray\nint a;\n")
        self.check("src/b.h", "// Generated by tools/x.py. Do not edit.\n// stray\nint a;\n")
        self.check("tools/g.py", "# Do not edit\n# stray\n")

    def test_other_files_ignored(self):
        self.check("docs/a.md", "<!-- a -->\n")

    def test_published_header_doc_comments(self):
        self.check("lib/bitexact/bitexact.h",
                   "/* A doc. */\nint f(void);\n/* A type. */\n#if X\ntypedef int t;\n#endif\n"
                   "int g(void); /* Trailing. */\n")

    def test_published_header_rejects_other_comments(self):
        self.check("lib/bitexact/bitexact.h",
                   "/* Two\n   lines. */\nint f(void);\n/* Orphan. */\n\nint g(void);\n"
                   "/* Stacked one. */\n/* Stacked two. */\nint h(void);\n", [1, 4, 7])

    def test_unpublished_header_doc_comment_rejected(self):
        self.check("src/a.h", "/* A doc. */\nint f(void);\n", [1])

    def test_todo_without_issue_rejected(self):
        self.check("src/a.cpp", "// TODO: later\nint a;\n", [1])
        self.check("tools/a.py", "# TODO later\n", [1])

    def test_todo_open_issue_check(self):
        self.repo.write("src/a.cpp", "// TODO(#1): a\n// TODO(#2): b\n// TODO(#3): c\n// TODO(#4): d\n")
        self.repo.commit("change")
        issues = {1: {"state": "open"}, 2: {"state": "closed"},
                  3: {"state": "open", "pull_request": {}}, 4: None}
        found = self.repo.lint(fetch=issues.get)
        self.assertEqual([line for _, line, _ in found], [2, 3, 4], found)

    def test_main_exit_codes(self):
        self.repo.write("src/a.cpp", "// stray\n")
        self.repo.commit("change")
        cwd = Path.cwd()
        try:
            os.chdir(self.repo.root)
            with contextlib.redirect_stdout(io.StringIO()) as out:
                self.assertEqual(commentlint.main(["HEAD~1...HEAD"]), 1)
            self.assertIn("src/a.cpp:1:", out.getvalue())
            self.repo.write("src/a.cpp", "int a;\n")
            self.repo.commit("fix")
            self.assertEqual(commentlint.main(["HEAD~2...HEAD"]), 0)
        finally:
            os.chdir(cwd)


if __name__ == "__main__":
    unittest.main()
