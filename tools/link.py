# --- compiling -----------------------------------------------------------------

def compile_all(jobs: int) -> tuple[list[Path], list[tuple[Path, str]]]:
    """Every source file's object, through tools/progress.py's cache. The gap
    regions' sources (tools/sources.py's `gap` files) are left out: tools/gapcheck.py's gap_objects
    gives the builds those whose source matches."""
    from progress import compile_cached

    # In link order: data, library code, then game code (tools/sources.py).
    sources = files_of_kind("data", "library", "game")

    def cached(src: Path) -> bool:
        key = source_key(src, DEFAULT_FLAGS + COMPILE_SCHEME)
        stamp = ROOT / "build/progress" / src.relative_to(SRC).with_suffix(".key")
        return stamp.exists() and stamp.read_text() == key and stamp.with_suffix(".obj").exists()

    stale = [s for s in sources if not cached(s)]
    if stale:
        print(f"compiling {len(stale)} file(s) not in build/progress ...", file=sys.stderr)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        results = dict(zip(sources, pool.map(compile_cached, sources)))
    objects, failed = [], []
    for src in sources:
        obj, log = results[src]
        if obj is None:
            failed.append((src, log))
        else:
            objects.append(obj)
    return objects, failed


# --- the generated global data --------------------------------------------------

def build_data(symbols: dict[str, int]) -> tuple[list[Path], dict[int, str]]:
    """Compile link/data.cpp, emit the globals it and the data files omit, and
    return the two objects with address -> the symbol each defines (and each
    data file's definition)."""
    BUILD.mkdir(parents=True, exist_ok=True)
    compile_data = ROOT / "tools/wcl"
    objects = []
    by_addr: dict[int, str] = {}

    def compile_one(src: Path, out: Path) -> bool:
        cmd = [str(compile_data), "/c", *DEFAULT_FLAGS.split(), f"/I{winpath(ROOT / 'include')}",
               f"/Fo{winpath(out)}", winpath(src)]
        proc = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
        if proc.returncode != 0 or not out.exists():
            print((proc.stdout + proc.stderr).replace("\r", ""), file=sys.stderr)
            return False
        objects.append(out)
        return True

    if DATA_CPP.exists():
        out = BUILD / "data.obj"
        if not compile_one(DATA_CPP, out):
            raise SystemExit("link/data.cpp did not compile")
    else:
        out = None

    # The data the data files define (compiled with the rest of src/ by compile_all).
    extents = data_source_extents(symbols)
    sources: dict[int, str] = {a: name for a, _, name, _ in extents}

    # A class's vtable the compiler emits (??_7...) is the one definition of
    # its address: the files that store it by hand (DAT_004fc980) mean it too.
    for name, addr in symbols.items():
        if name.startswith("??_7") and addr not in sources:
            sources[addr] = name

    # Extra globals: those globals.csv lists but neither data.cpp nor a data file defines.
    rows = global_rows()
    rows = {a: r for a, r in rows.items() if GLOBAL_LO <= a < GLOBAL_HI}
    have = (set(defined_addresses(out, symbols)) if out else set()) | set(sources)
    # What the code reaches inside a data file's global (a field, an entry: the
    # tree's DAT_005086e0 is a field of g_unitMessages[0]) is that global.
    have |= {a for a in rows if inside(extents, a)}
    extra = {a: r for a, r in rows.items() if a not in have}
    if extra:
        cpp = BUILD / "extra_data.cpp"
        write_extra_data(extra, cpp)
        out = BUILD / "extra_data.obj"
        if not compile_one(cpp, out):
            raise SystemExit("the generated global data did not compile")

    for out in objects:
        for addr, sym in defined_addresses(out, symbols).items():
            by_addr[addr] = sym
    by_addr.update(sources)
    return objects, by_addr


def data_source_extents(symbols: dict[str, int]) -> list[tuple[int, int, str, str]]:
    """(address, size, symbol, source file) of every global a data file defines,
    from its compiled object (tools/progress.py's cache, which compile_all
    fills): a global runs from its symbol to the next one in its section."""
    from place import parse
    out = []
    for src in files_of_kind("data"):
        obj_path = ROOT / "build/progress" / src.relative_to(SRC).with_suffix(".obj")
        if not obj_path.exists():
            continue
        obj = parse(obj_path)
        for name, sym in obj.externals.items():
            sec = obj.secs[sym.section - 1]
            if sec.is_code or name.startswith(("??_C@", "__real@")):
                continue
            addr = address_of(name, symbols)
            if addr is not None:
                lo, hi = sec.slice_at(sym.value)
                out.append((addr, hi - lo, name, relative(src)))
    return sorted(out)


def inside(extents: list[tuple[int, int, str, str]], addr: int) -> tuple[int, int, str, str] | None:
    """The extent holding addr, if any."""
    for e in extents:
        if e[0] <= addr < e[0] + max(e[1], 1):
            return e
    return None


# --- the missing import libraries -----------------------------------------------

def build_win32_lib() -> Path:
    """WIN32.LIB: WINMM.LIB with its DLL renamed. GOG's no-CD music fix
    renamed the exe's WINMM.dll import to WIN32.dll, its own winmm that plays
    the CD tracks from music/*.mp3 (with the code patch in
    data/exe_patches.csv); linked against WINMM.LIB, the game opens Wine's
    cdaudio device instead, finds no CD and disables the music options. The
    names are the same length, so the archive's offsets still hold."""
    from linkcheck import LIBDIR
    lib = BUILD / "WIN32.LIB"
    lib.parent.mkdir(parents=True, exist_ok=True)
    lib.write_bytes((LIBDIR / "WINMM.LIB").read_bytes().replace(b"WINMM.dll", b"WIN32.dll"))
    return lib


def build_import_libs() -> list[Path]:
    """Build SMACKW32.LIB and DPLAYX.LIB from .def files with LIB.EXE, and WIN32.LIB."""
    BUILD.mkdir(parents=True, exist_ok=True)
    out = [build_win32_lib()]
    for name, exports in (("SMACKW32", SMACKW32_EXPORTS), ("DPLAYX", DPLAYX_EXPORTS)):
        def_ = BUILD / f"{name}.def"
        lib = BUILD / f"{name}.LIB"
        lines = [f"LIBRARY {name}", "EXPORTS"]
        for cname, argbytes, ordinal in exports:
            lines.append(f"    {cname}@{argbytes} @{ordinal}")
        def_.write_text("\n".join(lines) + "\n")
        proc = subprocess.run([str(ROOT / "tools/wlib"), f"/def:{winpath(def_)}", f"/out:{winpath(lib)}"],
                              capture_output=True, text=True, cwd=ROOT)
        if proc.returncode != 0 or not lib.exists():
            raise SystemExit(f"could not build {lib.name}:\n{proc.stdout}{proc.stderr}")
        out.append(lib)
    return out


STUB_ARG_SIZES = sorted({ab for _, ab, _ in SMACKW32_EXPORTS + DPLAYX_EXPORTS})


def build_stub_dll(directory: Path) -> Path:
    """Build a no-op SMACKW32.dll next to the exe. The real Smacker decoder
    ships with the game; without it the loader stops before any game code
    runs, so the stub lets the image reach an honest failure instead."""
    c = BUILD / "smackw32_stub.c"
    lines = ["// Generated by tools/link.py --stub. A no-op stand-in for the",
             "// Smacker decoder the game ships; it exists so the linked image loads.",
             ""]
    for ab in STUB_ARG_SIZES:
        params = ", ".join(f"int a{i}" for i in range(ab // 4)) or "void"
        lines.append(f"void __stdcall stub{ab}({params}) {{}}")
    c.write_text("\n".join(lines) + "\n")

    obj = BUILD / "smackw32_stub.obj"
    proc = subprocess.run([str(ROOT / "tools/wcl"), "/c", "/O2", "/MT",
                           f"/Fo{winpath(obj)}", winpath(c)],
                          capture_output=True, text=True, cwd=ROOT)
    if proc.returncode != 0 or not obj.exists():
        raise SystemExit(f"the smackw32 stub did not compile:\n{proc.stdout}{proc.stderr}")

    def_ = BUILD / "smackw32_stub.def"
    lines = ["LIBRARY SMACKW32", "EXPORTS"]
    for cname, argbytes, ordinal in SMACKW32_EXPORTS:
        lines.append(f"    {cname}@{argbytes}=_stub{argbytes}@{argbytes} @{ordinal}")
    def_.write_text("\n".join(lines) + "\n")

    dll = directory / "SMACKW32.DLL"
    proc = subprocess.run([str(ROOT / "tools/wlink"), "/DLL", "/nologo", f"/OUT:{winpath(dll)}",
                           winpath(obj), f"/def:{winpath(def_)}"],
                          capture_output=True, text=True, cwd=ROOT)
    if proc.returncode != 0 or not dll.exists():
        raise SystemExit(f"the smackw32 stub did not link:\n{proc.stdout}{proc.stderr}")
    return dll


# --- the C++ static initialisers ---------------------------------------------------

EXE = ROOT / "orig/TotalA.exe"
PROGRESS = ROOT / "data/progress.csv"
FUNCTIONS = ROOT / "data/functions.csv"


def fix_initialisers(objects: list[Path]) -> list[Path]:
    """Make the image construct exactly the global objects the original does.

    A file that defines a global object only so that a function matches (the
    global's constructor is called from a static initialiser the compiler
    emits, `_$E<n>`) adds that initialiser to every link, although the
    original never calls it: its constructor may be another function, or
    take arguments the placeholder declaration leaves out (0x462cc0.cpp's
    `_$E4` calls Class_00462d30's constructor with none, and the one at its
    address pops one). So every object's .CRT$XCU sections are dropped except
    the initialisers the original's table holds, and the original's
    initialisers that the tree spells as ordinary functions (FUN_004205f0) get
    a table entry of their own, in the original's order."""
    with PROGRESS.open() as fh:
        rows = {int(r["address"], 16): (r["file"], r["symbol"]) for r in csv.DictReader(fh)}
    wanted: dict[str, list[str]] = defaultdict(list)     # source file -> initialiser symbols
    for fn in original_initialisers():
        if fn in rows:
            wanted[rows[fn][0]].append(rows[fn][1])
    out_dir = BUILD / "objs"
    out_dir.mkdir(parents=True, exist_ok=True)
    result: list[Path] = []
    kept = removed = added = 0
    for obj in objects:
        if obj.is_relative_to(ROOT / "build/progress"):
            src = str(Path("src") / obj.relative_to(ROOT / "build/progress").with_suffix(".cpp"))
        else:
            src = ""        # a gap region's object (build/gap/): the original runs none of its own
        data = bytearray(obj.read_bytes())
        _, nsects, _, symptr, nsyms, opthdr, _ = struct.unpack_from("<HHIIIHH", data, 0)
        strtab = bytes(data[symptr + nsyms * 18:])
        names = {}
        i = 0
        while i < nsyms:
            raw = data[symptr + i * 18: symptr + i * 18 + 18]
            if raw[:4] == b"\0\0\0\0":
                off = struct.unpack_from("<I", raw, 4)[0]
                names[i] = strtab[off:strtab.index(b"\0", off)].decode("latin-1")
            else:
                names[i] = bytes(raw[:8]).split(b"\0", 1)[0].decode("latin-1")
            i += 1 + raw[17]
        changed = False
        for sidx in range(nsects):
            hdr = 20 + opthdr + sidx * 40
            if bytes(data[hdr:hdr + 8]).rstrip(b"\0") != b".CRT$XCU":
                continue
            relptr, nrel = struct.unpack_from("<I", data, hdr + 24)[0], struct.unpack_from("<H", data, hdr + 32)[0]
            targets = [names.get(struct.unpack_from("<I", data, relptr + r * 10 + 4)[0]) for r in range(nrel)]
            if any(t in wanted.get(src, ()) for t in targets):
                kept += 1
                continue
            chars = struct.unpack_from("<I", data, hdr + 36)[0]
            struct.pack_into("<I", data, hdr + 36, chars | IMAGE_SCN_LNK_REMOVE)
            removed += 1
            changed = True
        if changed:
            patched = out_dir / obj.name
            patched.write_bytes(bytes(data))
            result.append(patched)
        else:
            result.append(obj)
        # The original's initialisers the tree spells as ordinary functions.
        for sym in wanted.get(src, ()):
            if not sym.startswith("_$E"):
                entry = out_dir / f"{obj.stem}_init.obj"
                write_init_object(sym, entry)
                result.append(entry)
                added += 1
    print(f"static initialisers: {kept + added} as in the original ({kept} from the objects, {added} added), "
          f"{removed} dropped", file=sys.stderr)
    return result


# --- /ORDER: the original's function order --------------------------------------

def build_order(map_path: Path, out: Path) -> Path:
    """Write the /ORDER list for a link whose map is map_path.

    With an /ORDER list LINK lays the named functions out first, in the order
    given, so listing every game function in original-address order reproduces
    the original's code order wherever the objects allow it. A function whose
    body LINK keeps from another object (a copy kept so that it inlines,
    docs/consolidation.md) is named by the symbol the baseline link put at that
    address, so the copy is ordered at the function's own rank too."""
    from check import load_symbols
    from carve import Namer
    from imagecmp import build_index
    from linkcmp import read_map
    from place import layout

    ranks: dict[int, list[str]] = defaultdict(list)
    for row in csv.DictReader(PROGRESS.open()):
        if row["status"] == "matched" and row["symbol"]:
            ranks[int(row["address"], 16)].append(row["symbol"])
    game = {int(r["address"], 16) for r in csv.DictReader(FUNCTIONS.open())
            if r["kind"] in ("game", "gap")}
    img, placer = layout()
    namer = Namer(img, placer)
    index = build_index(img, placer, namer, read_map(map_path), load_symbols(), identity=False)
    for line in map_path.read_text(errors="replace").splitlines():
        m = re.match(r"\s*([0-9a-f]{4}):[0-9a-f]{8}\s+(\S+)\s+([0-9a-f]{8})\s*(.*)$", line)
        if m is None or m.group(1) != "0001":
            continue
        sym, va, flags = m.group(2), int(m.group(3), 16), m.group(4).split()
        if not flags or "f" not in flags[:-1] or flags[-1].endswith(("stubs.obj", "aliases.obj")):
            continue
        orig, _ = index.translate(va)
        if orig in game and sym not in ranks[orig]:
            ranks[orig].append(sym)
    out.write_text("\n".join(s for a in sorted(ranks) for s in ranks[a]) + "\n")
    return out


# --- linking --------------------------------------------------------------------

def link(objects: list[Path], output: Path, verbose: bool, force_unresolved: bool,
         map_path: Path | None = None, libs: tuple[str, ...] = LIBS,
         order: Path | None = None) -> int:
    BUILD.mkdir(parents=True, exist_ok=True)
    rsp = BUILD / "objects.rsp"
    rsp.write_text("\n".join(winpath(o) for o in objects) + "\n")
    cmd = [str(ROOT / "tools/wlink"), "/nologo", "/OPT:NOREF", "/INCREMENTAL:NO",
           "/SUBSYSTEM:WINDOWS", f"/OUT:{winpath(output)}", f"@{winpath(rsp)}", *libs]
    if map_path is not None:
        cmd.insert(2, f"/MAP:{winpath(map_path)}")
    if order is not None:
        cmd.insert(2, f"/ORDER:@{winpath(order)}")
    if force_unresolved:
        cmd[2:2] = ["/FORCE:UNRESOLVED", "/FORCE:MULTIPLE"]
    else:
        # The tree has 95 known duplicate copies kept in callers' files so they
        # inline (docs/consolidation.md); they are not missing code, so they are
        # folded. Every external must resolve, which is what this mode checks.
        cmd[2:2] = ["/FORCE:MULTIPLE"]
    print(f"linking {len(objects):,} objects -> {output.relative_to(ROOT)}", file=sys.stderr)
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
    log = (proc.stdout + proc.stderr).replace("\r", "")
    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / "link.log").write_text(log)
    report(log, verbose)
    return proc.returncode


def report(log: str, verbose: bool) -> None:
    errors = re.findall(r"error (LNK\d+): (.*)", log)
    counts = Counter(code for code, _ in errors)
    duplicates = [line for line in log.splitlines() if "warning LNK4006" in line]
    unresolved = [msg for code, msg in errors if code == "LNK2001"]
    print(f"LINK: {len(errors):,} errors, {len(duplicates):,} duplicate warnings "
          f"({', '.join(f'{c} {n:,}' for c, n in counts.most_common()) or 'none'})")
    if unresolved:
        print(f"  {len(set(unresolved)):,} distinct unresolved symbols, e.g.:")
        for msg in sorted(set(unresolved))[:10 if not verbose else len(set(unresolved))]:
            print("   ", msg)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--strict", action="store_true",
                    help="no /FORCE:UNRESOLVED; generate the missing stubs and import libraries")
    ap.add_argument("--stub", action="store_true",
                    help="the same as --strict, naming the generated stubs explicitly")
    ap.add_argument("--carve", action="store_true",
                    help="link with what has no source carved from the exe (tools/carve.py), the "
                         "game's data laid out in the original's order; implies --stub")
    ap.add_argument("--output", type=Path, default=BUILD / "TotalA.exe")
    ap.add_argument("--map", action="store_true", help="also write build/link/TotalA.map")
    ap.add_argument("--no-exe-patches", action="store_true",
                    help="with --carve, leave out data/exe_patches.csv (GOG's no-CD music patch)")
    ap.add_argument("--order", action="store_true",
                    help="add /ORDER listing the game functions in their original order "
                         "(an extra link pass to read the baseline map)")
    ap.add_argument("--jobs", type=int, default=None, help="parallel compiles (default: all cores)")
    ap.add_argument("--verbose", "-v", action="store_true")
    args = ap.parse_args()

    output = args.output if args.output.is_absolute() else ROOT / args.output
    stub_mode = args.strict or args.stub or args.carve

    objects, failed = compile_all(args.jobs)
    if failed:
        for src, log in failed:
            print(f"{src}: {log}", file=sys.stderr)
        raise SystemExit(f"{len(failed)} file(s) did not compile")
    symbols, _, _ = load_known()
    carved: list[Path] = []
    extra: dict[str, str] = {}
    if args.carve:
        from carve import THIRD_PARTY_OBJS, carve, library_aliases
        result = carve(objects)
        carved = result.objects
        gaps = result.gap_sources
        # The game's data from source (link/data.cpp and the globals it leaves
        # out; the data files are among the objects), what origdata.obj still holds,
        # and zlib, which the original links too.
        data_objs, data_addr = build_data(symbols)
        data_addr.update(result.data_names)
        data_objs += list(THIRD_PARTY_OBJS)
        extra = library_aliases(objects + gaps, symbols, result)
    else:
        from gapcheck import gap_objects
        gaps = [g.path for _, g in sorted(gap_objects().items())]
        data_objs, data_addr = build_data(symbols)
    if gaps:
        print(f"{len(gaps)} gap region(s) built from source (tools/gapcheck.py)")

    libs = library_symbols(set(CRT_LIBS) | set(IMPORT_LIBS))
    import_libs: list[Path] = []
    if stub_mode:
        import_libs = build_import_libs()
        for lib in import_libs:
            for name in archive_symbols(lib):
                libs.setdefault(name, lib.name)

    aliases_path = BUILD / "aliases.obj"
    aliases = build_aliases(objects + gaps + carved + data_objs, symbols, data_addr, libs, aliases_path,
                            extra=extra,
                            winmain_addr=WINMAIN_ADDR if stub_mode and not args.carve else None,
                            data_fallback=stub_mode)
    print(f"{len(objects):,} objects, {len(aliases):,} aliases, {len(data_addr):,} globals at known addresses")

    # The carved data goes first: where a compiled object defines a global too,
    # LINK keeps the first definition, the original's, at its full size.
    game = fix_initialisers(objects + gaps) if stub_mode else list(objects) + gaps
    if args.carve:
        from carve import order_data, patch_objects
        game = order_data(patch_objects(game, result), result)
        data_objs = order_data(data_objs, result)
    link_objects = carved[:1] + game + carved[1:] + list(data_objs)
    # The icon, cursor and version resource, compiled from src/res/.
    from resources import build as build_resources
    link_objects.append(build_resources())
    if stub_mode:
        missing = unresolved_names(link_objects, set(aliases), libs)
        funcs = [n for n, is_func in missing.items() if is_func]
        data = [n for n, is_func in missing.items() if not is_func]
        stubs = BUILD / "stubs.obj"
        write_stub_object(funcs, data, stubs)
        print(f"stub mode: {len(funcs):,} function stubs and {len(data):,} data stubs "
              f"in {stubs.relative_to(ROOT)}")
        link_objects += [stubs, aliases_path]
        link_objects += import_libs
    else:
        link_objects += [aliases_path]

    # The carved link always writes its map: the hand patches move with it.
    map_path = BUILD / "TotalA.map" if args.map or args.carve else None
    # The generated WIN32.LIB stands in for WINMM.LIB (see build_win32_lib).
    libs = tuple(l for l in LIBS if not (stub_mode and l == "WINMM.LIB"))
    order_path = None
    if args.order:
        # The /ORDER list names the functions by the symbols LINK keeps, which
        # only a baseline link's map can say, so link once more without it.
        prelim = BUILD / "linkorder-baseline.exe"
        link(link_objects, prelim, args.verbose, force_unresolved=not stub_mode,
             map_path=prelim.with_suffix(".map"), libs=libs)
        order_path = build_order(prelim.with_suffix(".map"), BUILD / "linkorder.txt")
        print(f"/ORDER: {order_path.relative_to(ROOT)}", file=sys.stderr)
    rc = link(link_objects, output, args.verbose, force_unresolved=not stub_mode, map_path=map_path,
              libs=libs, order=order_path)
    if rc == 0 and output.exists():
        if args.carve and not args.no_exe_patches:
            from exepatch import apply_linked
            lines = apply_linked(output, map_path)
            print(f"data/exe_patches.csv: {len(lines)} hand patches applied after the link")
            print("\n".join(lines))
        print(f"{output.relative_to(ROOT)}: {output.stat().st_size:,} bytes")
        if stub_mode:
            dll = build_stub_dll(output.parent)
            print(f"stub mode: {dll.relative_to(ROOT)} (no-op Smacker decoder) beside the exe")
    raise SystemExit(rc)


if __name__ == "__main__":
    main()
