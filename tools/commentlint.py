"""Report comments on added lines that AGENTS.md ("Comments in code") disallows.

    uv run tools/commentlint.py [RANGE]          # default origin/moddable...HEAD
    python3 tools/commentlint.py origin/main...HEAD
    uv run tools/commentlint.py --all            # every line of every tracked file

Checks the lines RANGE adds in C and C++ (.c .cpp .h .hpp .inc) and Python
(.py) files, so the matching notes still in the decompiled sources do not
fail until #35 removes them and switches this to --all. A comment is allowed
when it is:

  * a TODO(#n): text, where #n is an open issue (checked when GITHUB_TOKEN and
    GITHUB_REPOSITORY are set, as in CI, otherwise skipped with a note);
  * a directive that a tool reads, listed in DIRECTIVES, alone on its line;
  * in a published interface header (PUBLISHED_INTERFACES), a one-line doc
    comment directly above a declaration or trailing on its line.

Exempt: generated files, Python docstrings (they are not comments), and
shebang lines. Prints file:line: reason for each violation and exits 1 if
there are any. Standard library only.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tokenize
import urllib.error
import urllib.request
from dataclasses import dataclass
from io import StringIO
from pathlib import Path

DEFAULT_RANGE = "origin/moddable...HEAD"

C_SUFFIXES = {".c", ".cpp", ".h", ".hpp", ".inc"}
PY_SUFFIXES = {".py"}

PUBLISHED_INTERFACES = {
    "lib/bitexact/bitexact.h",
}

GENERATED_FILES = {
    "src/harness/trace_schema.h",
}

GENERATED_MARKER = re.compile(r"generated by|do not edit", re.I)
GENERATED_HEAD_LINES = 5

TODO = re.compile(r"TODO\(#(\d+)\):\s*\S")

DIRECTIVES = [
    ("FUNCTION", re.compile(r"FUNCTION:\s*0x[0-9a-fA-F]+(\s+\S+)?$"),
     "tools/sources.py, check.py, checkall.py, unitmap.py, rename.py"),
    ("GLOBAL", re.compile(r"GLOBAL:\s*0x[0-9a-fA-F]+$"),
     "tools/sources.py, place.py"),
    ("ENTRY", re.compile(r"ENTRY:\s*0x[0-9a-fA-F]+(\s+\S+)?$"),
     "tools/gapcheck.py, rename.py"),
    ("FLAGS", re.compile(r"FLAGS:\s*\S.*$"),
     "tools/check.py, gametypes.py"),
]


@dataclass
class Comment:
    start: int
    end: int
    body: str
    code_before: bool


RAW_OPEN = re.compile(r'"([^()\\ ]{0,16})\(')
RAW_PREFIX = re.compile(r"(?<![A-Za-z0-9_])(?:u8|u|U|L)?R$")


def scan_c(text):
    """Every comment in C or C++ source, skipping string and char literals."""
    comments = []
    i, n, line = 0, len(text), 1
    code_lines = set()
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if c == "\n":
            line += 1
            i += 1
        elif two == "//":
            start = line
            j = i + 2
            while j < n and not (text[j] == "\n" and text[j - 1] != "\\"):
                if text[j] == "\n":
                    line += 1
                j += 1
            comments.append(Comment(start, line, text[i + 2:j], start in code_lines))
            i = j
        elif two == "/*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            body = text[i + 2:max(i + 2, j - 2)]
            start = line
            line += text.count("\n", i, j)
            comments.append(Comment(start, line, body, start in code_lines))
            i = j
        elif c == '"' or (c == "'" and not (i and text[i - 1].isdigit())):
            m = RAW_OPEN.match(text, i) if c == '"' and RAW_PREFIX.search(text, max(0, i - 3), i) else None
            end = text.find(")" + m.group(1) + '"', m.end()) if m else -1
            if m:
                j = n if end < 0 else end + len(m.group(1)) + 2
            else:
                j = i + 1
                while j < n and text[j] != c and text[j] != "\n":
                    j += 2 if text[j] == "\\" else 1
                j = min(j + 1, n)
            code_lines.update(range(line, line + text.count("\n", i, j) + 1))
            line += text.count("\n", i, j)
            i = j
        else:
            if not c.isspace():
                code_lines.add(line)
            i += 1
    return comments


def python_comments(text):
    """(line, text) of every Python comment token."""
    tokens = tokenize.generate_tokens(StringIO(text).readline)
    return [(t.start[0], t.string) for t in tokens if t.type == tokenize.COMMENT]


def is_generated(path, text):
    if path in GENERATED_FILES:
        return True
    head = text.splitlines()[:GENERATED_HEAD_LINES]
    return any(GENERATED_MARKER.search(h) for h in head)


def one_line_doc(comment, lines):
    """A one-line comment trailing a declaration or directly above one."""
    if comment.start != comment.end:
        return False
    if comment.code_before:
        return True
    below = lines[comment.end] if comment.end < len(lines) else ""
    below = below.strip()
    return bool(below) and not below.startswith(("//", "/*", "*/"))


def check_c(path, text, added):
    out, todos = [], []
    lines = text.splitlines()
    published = path in PUBLISHED_INTERFACES
    for c in scan_c(text):
        touched = [ln for ln in range(c.start, c.end + 1) if ln in added]
        if not touched:
            continue
        where = touched[0]
        body = c.body.strip()
        m = TODO.match(body)
        if m:
            todos.append((path, where, int(m.group(1))))
            continue
        if not c.code_before and any(d.match(body) for _, d, _ in DIRECTIVES):
            continue
        if published:
            if not one_line_doc(c, lines):
                out.append((where, "doc comment in a published interface must be one line, "
                                   "directly above a declaration or trailing it"))
            continue
        if body.startswith("TODO"):
            out.append((where, "TODO must read TODO(#n): text"))
        else:
            out.append((where, "comment outside the allowed forms (TODO(#n), "
                               "FUNCTION/GLOBAL/ENTRY/FLAGS directive)"))
    return out, todos


def check_python(path, text, added):
    out, todos = [], []
    try:
        found = python_comments(text)
    except (tokenize.TokenError, SyntaxError, IndentationError) as e:
        return [(1, f"cannot tokenize: {e}")], todos
    for line, comment in found:
        if line not in added:
            continue
        if line == 1 and comment.startswith("#!"):
            continue
        m = re.fullmatch(r"#\s*TODO\(#(\d+)\):\s*\S.*", comment)
        if m:
            todos.append((path, line, int(m.group(1))))
        elif comment.lstrip("# ").startswith("TODO"):
            out.append((line, "TODO must read # TODO(#n): text"))
        else:
            out.append((line, "Python comment outside the allowed forms (only # TODO(#n))"))
    return out, todos


def check_file(path, text, added):
    if is_generated(path, text):
        return [], []
    suffix = Path(path).suffix
    if suffix in PY_SUFFIXES:
        return check_python(path, text, added)
    return check_c(path, text, added)


def git(root, *args):
    r = subprocess.run(["git", "-c", "core.quotepath=false", *args], cwd=root,
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def added_lines(root, rev_range):
    """{path: set of added line numbers} from git diff -U0."""
    diff = git(root, "diff", "-U0", "--no-color", "--no-ext-diff", "--diff-filter=d",
               rev_range, "--")
    result, path = {}, None
    for row in diff.splitlines():
        if row.startswith("+++ "):
            path = row[6:].split("\t")[0] if row.startswith("+++ b/") else None
            if path:
                result.setdefault(path, set())
        elif row.startswith("@@") and path:
            m = re.match(r"@@ -\S+ \+(\d+)(?:,(\d+))? @@", row)
            start, count = int(m.group(1)), int(m.group(2) or 1)
            result[path].update(range(start, start + count))
    return result


def new_text(root, rev_range, path):
    m = re.search(r"\.\.\.?(.*)$", rev_range)
    if not m:
        return (Path(root) / path).read_text(errors="replace")
    return git(root, "show", f"{m.group(1) or 'HEAD'}:{path}")


def all_lines(root):
    result = {}
    for path in git(root, "ls-files").splitlines():
        text = (Path(root) / path).read_text(errors="replace")
        result[path] = set(range(1, text.count("\n") + 2))
    return result


def fetch_issue(repo, number, token):
    req = urllib.request.Request(
        f"https://api.github.com/repos/{repo}/issues/{number}",
        headers={"Authorization": f"Bearer {token}",
                 "Accept": "application/vnd.github+json"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def check_todos(todos, fetch):
    """Violations for TODOs that do not name an open issue."""
    out, cache = [], {}
    for path, line, number in todos:
        if number not in cache:
            cache[number] = fetch(number)
        issue = cache[number]
        if issue is None:
            reason = f"TODO(#{number}): no such issue"
        elif "pull_request" in issue:
            reason = f"TODO(#{number}): #{number} is a pull request, not an issue"
        elif issue.get("state") != "open":
            reason = f"TODO(#{number}): issue #{number} is {issue.get('state')}, not open"
        else:
            continue
        out.append((path, line, reason))
    return out


def lint(root, rev_range=None, everything=False, fetch=None):
    """(violations as (path, line, reason), todos) for the added lines."""
    if everything:
        lines = all_lines(root)
    else:
        lines = added_lines(root, rev_range)
    violations, todos = [], []
    for path in sorted(lines):
        if Path(path).suffix not in C_SUFFIXES | PY_SUFFIXES or not lines[path]:
            continue
        text = (Path(root) / path).read_text(errors="replace") if everything \
            else new_text(root, rev_range, path)
        found, found_todos = check_file(path, text, lines[path])
        violations += [(path, line, reason) for line, reason in found]
        todos += found_todos
    if fetch:
        violations += check_todos(todos, fetch)
    return sorted(violations), todos


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("range", nargs="?", default=DEFAULT_RANGE)
    ap.add_argument("--all", action="store_true", help="check every line of every tracked file")
    args = ap.parse_args(argv)
    root = git(".", "rev-parse", "--show-toplevel").strip()
    token = os.environ.get("GITHUB_TOKEN")
    repo = os.environ.get("GITHUB_REPOSITORY")
    fetch = (lambda n: fetch_issue(repo, n, token)) if token and repo else None
    violations, todos = lint(root, args.range, args.all, fetch)
    for path, line, reason in violations:
        print(f"{path}:{line}: {reason}")
    if not fetch and todos:
        print("note: open-issue check of TODOs skipped (GITHUB_TOKEN or GITHUB_REPOSITORY unset)")
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
